ALTER TABLE level_unlocks FORCE ROW LEVEL SECURITY;
CREATE POLICY own_rows ON level_unlocks USING (user_id = app_user()) WITH CHECK (user_id = app_user());
ALTER TABLE level_marks ENABLE ROW LEVEL SECURITY;
ALTER TABLE level_marks FORCE ROW LEVEL SECURITY;
CREATE POLICY own_rows ON level_marks USING (user_id = app_user()) WITH CHECK (user_id = app_user());
ALTER TABLE level_notices ENABLE ROW LEVEL SECURITY;
ALTER TABLE level_notices FORCE ROW LEVEL SECURITY;
CREATE POLICY own_rows ON level_notices USING (user_id = app_user()) WITH CHECK (user_id = app_user());
