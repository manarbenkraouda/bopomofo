-- Levels (app/levels.py): the guided path. Unlocks are permanent; known items are remembered so a drop can be noticed.
-- level_unlocks: one row per unlocked level ("level:2") or alphabet chapter ("chapter:medials"). Level 1 needs no row.
CREATE TABLE level_unlocks (
  user_id TEXT NOT NULL DEFAULT app_user(),
  key TEXT NOT NULL,
  ts DOUBLE PRECISION NOT NULL,
  PRIMARY KEY (user_id, key));

-- level_marks: items (a symbol or "tone:N") that reached three stars in an exercise. dropped_ts: when it slipped, NULL when known.
CREATE TABLE level_marks (
  user_id TEXT NOT NULL DEFAULT app_user(),
  exercise TEXT NOT NULL,
  item TEXT NOT NULL,
  known_ts DOUBLE PRECISION NOT NULL,
  dropped_ts DOUBLE PRECISION,
  PRIMARY KEY (user_id, exercise, item));

-- level_notices: what the learner is told once (kind: unlock, drop, back).
CREATE TABLE level_notices (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id TEXT NOT NULL DEFAULT app_user(),
  ts DOUBLE PRECISION NOT NULL,
  kind TEXT NOT NULL,
  key TEXT NOT NULL,
  title TEXT NOT NULL,
  text TEXT NOT NULL,
  seen BOOLEAN NOT NULL DEFAULT false);
CREATE INDEX level_notices_user ON level_notices(user_id, seen, id);

