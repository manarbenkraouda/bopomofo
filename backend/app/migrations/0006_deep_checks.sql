-- deep_checks (app/deep_check.py): the second, slower check of a missed speaking answer. One row per event.
-- mode: the DEEP_CHECK mode when the check ran. applied: the units, score, and levels were corrected (apply mode only).
-- parts: the checked parts [{pos, kind, expected, heard, verdict, delta | p_tone, ...}]. No audio and no model output is stored.
CREATE TABLE deep_checks (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id TEXT NOT NULL DEFAULT app_user(),
  event_id BIGINT NOT NULL UNIQUE REFERENCES events(id) ON DELETE CASCADE,
  ts DOUBLE PRECISION NOT NULL,
  status TEXT NOT NULL,
  verdict TEXT,
  score_before DOUBLE PRECISION,
  score_after DOUBLE PRECISION,
  parts JSONB,
  mode TEXT NOT NULL,
  applied BOOLEAN NOT NULL DEFAULT false,
  version TEXT,
  seconds DOUBLE PRECISION,
  notice_id BIGINT);
CREATE INDEX deep_checks_user ON deep_checks(user_id, ts);

ALTER TABLE deep_checks ENABLE ROW LEVEL SECURITY;
ALTER TABLE deep_checks FORCE ROW LEVEL SECURITY;
CREATE POLICY own_rows ON deep_checks USING (user_id = app_user()) WITH CHECK (user_id = app_user());
