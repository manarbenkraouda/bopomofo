-- Initial schema. Every table belongs to one user (the Clerk user id).
-- app_user() is the user of the current connection, set by the API for each request (app/db.py).
-- Row-level security shows and changes only that user's rows, and fills user_id on insert.

CREATE FUNCTION app_user() RETURNS text LANGUAGE sql STABLE AS $$
  SELECT NULLIF(current_setting('app.user_id', true), '')
$$;

CREATE TABLE sentences (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id TEXT NOT NULL DEFAULT app_user(),
  hanzi TEXT NOT NULL, english TEXT, words TEXT, topic TEXT, level TEXT,
  created DOUBLE PRECISION NOT NULL);
CREATE INDEX sentences_user ON sentences(user_id, id);

CREATE TABLE profile (
  user_id TEXT PRIMARY KEY DEFAULT app_user(),
  data TEXT NOT NULL);

CREATE TABLE events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id TEXT NOT NULL DEFAULT app_user(),
  ts DOUBLE PRECISION NOT NULL, day TEXT NOT NULL, area TEXT NOT NULL, mode TEXT,
  item TEXT NOT NULL, ok INTEGER NOT NULL, first_try INTEGER, score DOUBLE PRECISION, ms INTEGER, tries INTEGER,
  help INTEGER NOT NULL DEFAULT 0, replays INTEGER, legacy INTEGER NOT NULL DEFAULT 0, details TEXT);
CREATE INDEX events_day ON events(user_id, day, area);
CREATE INDEX events_ts ON events(user_id, ts);

CREATE TABLE units (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id TEXT NOT NULL DEFAULT app_user(),
  event_id BIGINT NOT NULL REFERENCES events(id) ON DELETE CASCADE,
  ts DOUBLE PRECISION NOT NULL, day TEXT NOT NULL, area TEXT NOT NULL, mode TEXT, kind TEXT NOT NULL,
  expected TEXT NOT NULL, actual TEXT, ok INTEGER, pos INTEGER NOT NULL DEFAULT 0, try_n INTEGER NOT NULL DEFAULT 0,
  help INTEGER NOT NULL DEFAULT 0, ctx TEXT, lex TEXT, prev TEXT, next TEXT, source TEXT,
  uncertain INTEGER NOT NULL DEFAULT 0, extra TEXT);
CREATE INDEX units_kind ON units(user_id, kind, area, expected);
CREATE INDEX units_day ON units(user_id, day);
CREATE INDEX units_event ON units(event_id);

CREATE TABLE days (
  user_id TEXT NOT NULL DEFAULT app_user(),
  day TEXT NOT NULL, seconds INTEGER NOT NULL DEFAULT 0, goal_min INTEGER,
  PRIMARY KEY (user_id, day));

CREATE TABLE meta (
  user_id TEXT NOT NULL DEFAULT app_user(),
  key TEXT NOT NULL, value TEXT,
  PRIMARY KEY (user_id, key));

CREATE TABLE plans (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id TEXT NOT NULL DEFAULT app_user(),
  ts DOUBLE PRECISION NOT NULL, status TEXT NOT NULL, source TEXT, model TEXT,
  diagnosis TEXT, reason TEXT, digest TEXT, raw TEXT, error TEXT, done_ts DOUBLE PRECISION,
  headline TEXT, story TEXT);
CREATE INDEX plans_user ON plans(user_id, status, id);

CREATE TABLE steps (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id TEXT NOT NULL DEFAULT app_user(),
  plan_id BIGINT NOT NULL REFERENCES plans(id) ON DELETE CASCADE, pos INTEGER NOT NULL,
  type TEXT NOT NULL, title TEXT NOT NULL, why TEXT, params TEXT NOT NULL, target INTEGER NOT NULL, minutes INTEGER,
  status TEXT NOT NULL DEFAULT 'open', done_ts DOUBLE PRECISION, skip_reason TEXT, checked_n INTEGER NOT NULL DEFAULT 0);
CREATE INDEX steps_plan ON steps(plan_id, pos);

CREATE TABLE milestones (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id TEXT NOT NULL DEFAULT app_user(),
  ts DOUBLE PRECISION NOT NULL, plan_id BIGINT, title TEXT NOT NULL, why TEXT,
  criterion TEXT NOT NULL, status TEXT NOT NULL DEFAULT 'active', done_ts DOUBLE PRECISION);
CREATE INDEX milestones_user ON milestones(user_id, status);

CREATE TABLE coach_calls (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id TEXT NOT NULL DEFAULT app_user(),
  ts DOUBLE PRECISION NOT NULL, run TEXT, plan_id BIGINT, step_id BIGINT, stage TEXT NOT NULL,
  model TEXT, ms INTEGER, cost DOUBLE PRECISION, tokens INTEGER, ok INTEGER NOT NULL, error TEXT, response TEXT);
CREATE INDEX coach_calls_user ON coach_calls(user_id, ts);
CREATE INDEX coach_calls_run ON coach_calls(run);
CREATE INDEX coach_calls_plan ON coach_calls(plan_id);

CREATE TABLE coach_notes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id TEXT NOT NULL DEFAULT app_user(),
  ts DOUBLE PRECISION NOT NULL, plan_id BIGINT, step_id BIGINT, kind TEXT NOT NULL, text TEXT NOT NULL);
CREATE INDEX coach_notes_user ON coach_notes(user_id, plan_id, step_id);

DO $$
DECLARE t text;
BEGIN
  FOREACH t IN ARRAY ARRAY['sentences','profile','events','units','days','meta','plans','steps','milestones','coach_calls','coach_notes'] LOOP
    EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
    EXECUTE format('ALTER TABLE %I FORCE ROW LEVEL SECURITY', t);
    EXECUTE format('CREATE POLICY own_rows ON %I USING (user_id = app_user()) WITH CHECK (user_id = app_user())', t);
  END LOOP;
END
$$;
