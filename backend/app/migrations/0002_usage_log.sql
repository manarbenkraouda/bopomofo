-- Paid AI calls and new text-to-speech clips, for the limits of each user (app/limits.py).
-- kind: "ai" (cost in USD when the provider gives it) or "tts".
CREATE TABLE usage_log (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id TEXT NOT NULL DEFAULT app_user(),
  ts DOUBLE PRECISION NOT NULL, kind TEXT NOT NULL, cost DOUBLE PRECISION);
CREATE INDEX usage_log_user ON usage_log(user_id, kind, ts);

ALTER TABLE usage_log ENABLE ROW LEVEL SECURITY;
ALTER TABLE usage_log FORCE ROW LEVEL SECURITY;
CREATE POLICY own_rows ON usage_log USING (user_id = app_user()) WITH CHECK (user_id = app_user());
